//! Explicit statement, ordering, SQL error and external-observation contracts.
use crate::{BoundExpr, Cell, Column, Database, Plan, Row};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

/// Explicit result comparison semantics; ordered rows cannot be compared as bags.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ResultOrdering {
    /// Only row multiplicities are observable.
    Bag,
    /// Every row position is observable.
    Ordered,
}

/// Direction applies only to non-NULL comparisons; NULL placement is separate.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SortDirection {
    /// Smaller non-NULL values precede larger values.
    Ascending,
    /// Larger non-NULL values precede smaller values.
    Descending,
}

/// One lexicographic sorting component, evaluated against the unprojected input.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct OrderKey {
    /// Typed ordering expression.
    pub expression: BoundExpr,
    /// Non-NULL comparison direction.
    pub direction: SortDirection,
    /// Whether NULL precedes every non-NULL value.
    pub nulls_first: bool,
}

/// Phase is part of SQL failure evidence, distinct from engine or coverage errors.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum FailurePhase {
    /// SQLSTATE alone does not establish a planning/execution boundary.
    Unspecified,
    /// PostgreSQL planning or constant-folding failure.
    Planning,
    /// Failure while executing a statement.
    Statement,
    /// Failure while checking or ending a transaction.
    Commit,
}

/// An admitted external observation; no such event is generated by an unknown function.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum EffectEvent {
    /// An externally delivered signal request; immediate target exit is not implied.
    BackendTerminationRequested {
        /// Target identity in the explicitly supplied PostgreSQL backend inventory.
        pid: i32,
    },
    /// A server warning already emitted to the client; SQL rollback cannot retract it.
    SqlWarning {
        /// Five-character SQLSTATE of the warning.
        sqlstate: String,
        /// Exact message under the declared server message-language profile.
        message: String,
    },
    /// Physical version/header journal, independent of transactional row-data rollback.
    TupleVersion {
        /// Typed transition or abort residual tied to a stable input/candidate occurrence.
        observation: Box<crate::TupleVersionEvent>,
    },
    /// Relation lock acquired even when a locking query returns no rows.
    TableLock {
        /// Stable physical relation identifier.
        table: String,
        /// Explicit PostgreSQL relation lock mode.
        mode: String,
    },
    /// Row lock held after an admitted fixed-snapshot locking query.
    RowLock {
        /// Stable physical relation identifier.
        table: String,
        /// Stable occurrence index within the supplied physical table snapshot.
        occurrence: usize,
        /// Held PostgreSQL row-lock strength.
        strength: crate::RowLockMode,
    },
    /// A pending notification invocation; commit delivery is a separate de-duplicated transition.
    Notification {
        /// Resolved notification channel.
        channel: String,
        /// Exact payload.
        payload: String,
    },
    /// Newly granted transaction advisory ownership in one fixed-snapshot branch.
    AdvisoryLock {
        /// Namespace, owner and shared/exclusive mode of the acquired lock.
        held: crate::AdvisoryHeld,
    },
    /// A nontransactional sequence allocation.
    SequenceValue {
        /// Resolved sequence identifier.
        sequence: String,
        /// Allocated sequence value.
        value: i64,
    },
}

/// SQL rejection remains an execution outcome rather than disappearing from the model.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct SqlFailure {
    /// Five-character PostgreSQL SQLSTATE.
    pub sqlstate: String,
    /// Boundary at which the failure is observed.
    pub phase: FailurePhase,
    /// Named constraint, when PostgreSQL supplies that diagnostic field.
    pub constraint_name: Option<String>,
    /// Column diagnostic, independently of constraint identity.
    pub column_name: Option<String>,
    /// Rows exposed before failure; rollback does not erase them.
    pub exposed_rows: Vec<Row>,
    /// External observations retained across failure.
    pub effects: Vec<EffectEvent>,
}

/// Successful statement observations include state, counts, ordering and external effects.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct StatementSuccess {
    /// Catalog poststate when evaluation uses the explicit catalog-aware interface.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub catalog: Option<Box<crate::Catalog>>,
    /// Complete transactional table state after this statement.
    pub database: Database,
    /// Query or RETURNING result occurrences.
    pub rows: Vec<Row>,
    /// Whether the result must retain row positions.
    pub ordering: ResultOrdering,
    /// PostgreSQL affected-row count; matched unchanged UPDATE rows count.
    pub affected: u64,
    /// Command tag, independently of transaction termination semantics.
    pub command_tag: String,
    /// Admitted non-table observations.
    pub effects: Vec<EffectEvent>,
}

/// One admitted SQL behavior; engine/resource/coverage failures use the outer Result.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "status", content = "outcome", rename_all = "snake_case")]
pub enum StatementOutcome {
    /// Statement completed with explicit state and observations.
    Succeeded(StatementSuccess),
    /// Statement rejected with a preserved SQL error.
    SqlError(SqlFailure),
}

/// Complete finite behavior enumeration; exceeding capacity returns an error instead.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct OutcomeSet {
    /// All admitted behaviors, deduplicated by complete observable equality.
    pub outcomes: Vec<StatementOutcome>,
}

/// Explicit finite execution resources and supplied session values.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ExecutionContext {
    /// Explicit exclusive heap-header snapshot for system-column observations.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tuples: Option<crate::TupleContext>,
    /// Explicit nontransactional sequence state; allocation never consults a live database.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sequences: Option<crate::SequenceContext>,
    /// Complete fixed session ownership and pending-event context for explicit effect calls.
    #[serde(default)]
    pub session_effects: Option<crate::SessionEffectContext>,
    /// Closed backend snapshot for deterministic signal-request observations.
    #[serde(default)]
    pub backend_signals: Option<crate::BackendSignalContext>,
    /// Catalog-owned immutable SQL functions available to CHECK/default/index expression binding.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub functions: Option<crate::SqlFunctions>,
    /// Complete catalog identity inventory for context-sensitive relation-name lookup.
    #[serde(default)]
    pub catalog_lookup: Option<crate::CatalogLookup>,
    /// Explicit ownership/conflict snapshot required by locking operations.
    #[serde(default)]
    pub locks: Option<crate::LockContext>,
    /// Maximum complete behavior count; enumeration never truncates to this number.
    pub max_outcomes: usize,
    /// Maximum occurrences in every materialized intermediate relation.
    pub max_rows: usize,
    /// Declared context values; missing function/session inputs are coverage failures.
    pub settings: BTreeMap<String, Cell>,
    /// Explicit table constraints/defaults; writes require a complete target definition.
    #[serde(default)]
    pub table_metadata: BTreeMap<String, crate::TableSemantics>,
}

/// Stable mutation target with its complete physical schema.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct MutationTarget {
    /// Stable catalog identifier.
    pub table: String,
    /// Physical type/nullability metadata.
    pub schema: Vec<Column>,
}

/// Bound output projection shared by all mutations.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Returning {
    /// Expressions append xmin/xmax after physical columns; wildcard expansion excludes them.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub system_columns: bool,
    /// Explicit output metadata; empty means no RETURNING clause.
    pub schema: Vec<Column>,
    /// Expressions evaluated against the appropriate old or new row.
    pub expressions: Vec<BoundExpr>,
}

/// INSERT source values map to explicit target column positions.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct InsertPlan {
    /// Physical target columns explicitly defaulted in each literal VALUES occurrence.
    pub default_columns: Vec<Vec<usize>>,
    /// Explicit unique-conflict inference and action; absent means ordinary INSERT.
    pub conflict: Option<ConflictPlan>,
    /// Resolved target relation.
    pub target: MutationTarget,
    /// Source relation evaluated before publishing the candidate state.
    pub source: Plan,
    /// Target column index for each source result position.
    pub columns: Vec<usize>,
    /// New-row result projection.
    pub returning: Returning,
}

/// Unique arbiter inference is distinct from row-level UPDATE WHERE filtering.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum ConflictTarget {
    /// DO NOTHING may skip conflicts from any admitted unique constraint.
    Any,
    /// Infer nonpartial unique constraints on this exact set of physical positions.
    Columns(Vec<usize>),
    /// Infer indexes on these key positions only when this predicate implies their predicate.
    PredicateColumns {
        /// Physical column positions, independent of spelling/order in the inference clause.
        columns: Vec<usize>,
        /// Typed inference predicate; it does not filter INSERT source occurrences.
        predicate: Box<BoundExpr>,
    },
    /// Resolve one explicitly named unique or primary constraint.
    Constraint(String),
}

/// ON CONFLICT actions evaluate against existing-row columns followed by EXCLUDED columns.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum ConflictActionPlan {
    /// Skip the input occurrence without returning it or increasing affected count.
    Nothing,
    /// Apply simultaneous assignments when the conflict predicate is TRUE.
    Update {
        /// Existing-row targets; expressions may read the excluded proposal.
        assignments: Vec<Assignment>,
        /// Boolean row-level filter; UNKNOWN skips the conflict update.
        predicate: Box<BoundExpr>,
    },
}

/// A bound conflict rule requires runtime validation against complete constraint metadata.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct ConflictPlan {
    /// Declared arbiter inference target.
    pub target: ConflictTarget,
    /// Exact conflict behavior.
    pub action: ConflictActionPlan,
}

/// An assignment evaluates its expression against the original row.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Assignment {
    /// Physical target column index.
    pub column: usize,
    /// Old-row expression.
    pub expression: BoundExpr,
}

/// UPDATE retains old-row predicate and simultaneous assignment semantics.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct UpdatePlan {
    /// Optional FROM relation; predicates and expressions see target columns followed by source.
    pub source: Option<Plan>,
    /// Resolved target relation.
    pub target: MutationTarget,
    /// Only TRUE selects an occurrence.
    pub predicate: BoundExpr,
    /// Distinct target assignments, all evaluated against the old row.
    pub assignments: Vec<Assignment>,
    /// New-row result projection.
    pub returning: Returning,
}

/// DELETE returns selected old rows while retaining every unselected occurrence.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct DeletePlan {
    /// Optional USING relation; each matching target occurrence is still deleted at most once.
    pub source: Option<Plan>,
    /// Resolved target relation.
    pub target: MutationTarget,
    /// Only TRUE selects an occurrence.
    pub predicate: BoundExpr,
    /// Old-row result projection.
    pub returning: Returning,
}

/// Bound statement shape is separate from its execution and encoding capability.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum StatementPlan {
    /// Compiler-resolved relation ownership survives pruning and precedes row demand.
    Initialized {
        /// Sorted distinct physical table identities opened with ROW SHARE.
        relations: Vec<String>,
        /// Planned statement, including a retained planning failure when applicable.
        body: Box<StatementPlan>,
    },
    /// Same-snapshot CTE statements communicate through explicit RETURNING relations.
    With(WithPlan),
    /// Create an empty relation with persistent schema semantics.
    CreateTable(crate::CreateTablePlan),
    /// Store a prepared view definition without materializing its result.
    CreateView(crate::CreateViewPlan),
    /// Remove explicitly resolved view catalog objects.
    DropView(crate::DropViewPlan),
    /// Pure query plus explicit row-lock observations under a declared lock snapshot.
    LockedQuery(crate::LockedQueryPlan),
    /// A known SQL planning or constant pagination error, retained as a modeled outcome.
    Rejected {
        /// Complete SQL error diagnostic.
        failure: SqlFailure,
    },
    /// Pure query, possibly with observable ordering or pagination.
    Query(Plan),
    /// Insert occurrences into one table.
    Insert(InsertPlan),
    /// Update selected occurrences of one table.
    Update(UpdatePlan),
    /// Delete selected occurrences of one table.
    Delete(DeletePlan),
}

/// A lexical CTE binding has a compiler-reserved result identity, never an external table input.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct CteStatement {
    /// SQL-visible CTE name.
    pub name: String,
    /// Internal relation identity removed before publishing table state.
    pub table_id: String,
    /// Bound statement whose query/RETURNING rows populate that identity.
    pub statement: Box<StatementPlan>,
}

/// One WITH statement evaluates base reads against its original snapshot.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct WithPlan {
    /// Lexically ordered live read bindings and every writable binding.
    pub bindings: Vec<CteStatement>,
    /// Final statement supplies result rows and the PostgreSQL command tag.
    pub body: Box<StatementPlan>,
}
